import type { ReactNode, SVGProps } from "react";
import { cn } from "./cn";

/**
 * The popup's icon set — the exact stroke glyphs the approved design uses, drawn
 * locally so the extension takes no icon dependency and every glyph shares one
 * geometry (24 viewBox, `currentColor`, round caps/joins).
 *
 * Callers set the SIZE with a class (`size-[18px]`) and the COLOR by inheriting
 * text color, so an icon always matches the token color of the row it sits in.
 * `strokeWidth` defaults to 2 and is overridden where the design asks for a
 * lighter (1.8, bento tiles) or heavier (2.2 brand mark / 3 check) weight.
 *
 * This replaces the unicode glyph placeholders (`↗`, `⚑`, `✓`) and the
 * hand-inlined, mismatched SVGs that used to live in individual components.
 */

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children"> {
  className?: string;
  strokeWidth?: number;
}

function Icon({
  className,
  strokeWidth = 2,
  children,
  ...rest
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cn("shrink-0", className)}
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

